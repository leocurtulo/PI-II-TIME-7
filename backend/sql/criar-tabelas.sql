DROP TABLE comentario CASCADE CONSTRAINTS;
DROP TABLE demanda CASCADE CONSTRAINTS;
DROP TABLE usuario CASCADE CONSTRAINTS;
DROP TABLE projeto CASCADE CONSTRAINTS;

CREATE TABLE projeto (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 4) PRIMARY KEY,
    nome VARCHAR2(100) NOT NULL
);

CREATE TABLE usuario (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 5) PRIMARY KEY,
    nome VARCHAR2(100) NOT NULL,
    email VARCHAR2(100) NOT NULL UNIQUE,
    senha VARCHAR2(100) NOT NULL,
    perfil VARCHAR2(30) NOT NULL,
    CHECK (perfil IN ('Administrador', 'Líder de Projeto', 'Membro da Equipe'))
);

CREATE TABLE demanda (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 9) PRIMARY KEY,
    titulo VARCHAR2(150) NOT NULL,
    descricao VARCHAR2(1000) NOT NULL,
    tipo VARCHAR2(20) NOT NULL,
    prioridade VARCHAR2(10) NOT NULL,
    status VARCHAR2(20) DEFAULT 'Aberta' NOT NULL,
    projeto_id NUMBER NOT NULL,
    responsavel_id NUMBER,
    data_criacao DATE DEFAULT SYSDATE NOT NULL,
    data_atualizacao DATE DEFAULT SYSDATE NOT NULL,
    prazo DATE,
    FOREIGN KEY (projeto_id) REFERENCES projeto (id),
    FOREIGN KEY (responsavel_id) REFERENCES usuario (id),
    CHECK (tipo IN ('Tarefa', 'Defeito', 'Melhoria', 'Documentação')),
    CHECK (prioridade IN ('Crítica', 'Alta', 'Média', 'Baixa')),
    CHECK (status IN ('Aberta', 'Em andamento', 'Em revisão', 'Concluída', 'Cancelada'))
);

CREATE TABLE comentario (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 4) PRIMARY KEY,
    demanda_id NUMBER NOT NULL,
    usuario_id NUMBER NOT NULL,
    texto VARCHAR2(1000) NOT NULL,
    data_hora TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    FOREIGN KEY (demanda_id) REFERENCES demanda (id),
    FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);

