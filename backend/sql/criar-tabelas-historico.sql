-- Vínculo entre usuário e projeto: diz em quais projetos cada Líder/Membro trabalha.
-- O Administrador não precisa de vínculo (ele vê tudo).
CREATE TABLE projeto_usuario (
    projeto_id NUMBER NOT NULL,
    usuario_id NUMBER NOT NULL,
    PRIMARY KEY (projeto_id, usuario_id),
    FOREIGN KEY (projeto_id) REFERENCES projeto (id),
    FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);


-- Histórico: cada linha guarda UMA mudança em UMA demanda (quem mudou, o quê, de qual valor para qual)
CREATE TABLE historico (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demanda_id NUMBER NOT NULL,
    usuario_id NUMBER NOT NULL,
    campo VARCHAR2(30) NOT NULL,
    valor_anterior VARCHAR2(1000),
    valor_novo VARCHAR2(1000),
    data_hora TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    FOREIGN KEY (demanda_id) REFERENCES demanda (id),
    FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CHECK (campo IN ('titulo', 'descricao', 'tipo', 'prioridade', 'responsavel', 'prazo', 'status'))
);


